import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  entryPoints: [path.join(root, "src/services/food-image-codec.js")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["chrome110"],
  minify: true,
  legalComments: "none",
});
const output = path.join(root, "src/generated");
fs.mkdirSync(output, { recursive: true });
const notices = path.join(root, "assets/food-codec-notices");
fs.mkdirSync(notices, { recursive: true });
const bundledNotices = [];
for (const name of [
  "@zxing/browser",
  "@zxing/library",
  "@zxing/text-encoding",
  "ts-custom-error",
]) {
  const folder = path.join(root, "node_modules", name),
    licence = ["LICENSE", "LICENSE.md", "LICENSE.txt"].find((n) =>
      fs.existsSync(path.join(folder, n)),
    );
  if (!licence) throw Error("Missing licence for " + name);
  bundledNotices.push(
    name + "\n" + fs.readFileSync(path.join(folder, licence), "utf8"),
  );
  fs.copyFileSync(
    path.join(folder, licence),
    path.join(notices, name.replaceAll("/", "-").replace("@", "") + ".txt"),
  );
}
fs.writeFileSync(
  path.join(output, "food-image-codec.ts"),
  "// Generated by scripts/build-food-codec.mjs.\n" +
    "export const FOOD_IMAGE_CODEC=" +
    JSON.stringify(result.outputFiles[0].text) +
    ";\n" +
    "export const FOOD_CODEC_NOTICES=" +
    JSON.stringify(bundledNotices.join("\n\n")) +
    ";\n",
);
console.log(
  "Built isolated food photo and barcode codec with third-party notices.",
);
